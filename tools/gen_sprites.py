# ---------------------------------------------------------------------------
# Encoding
# ---------------------------------------------------------------------------

def parse_row(row, label, y):
    """Turn one line of ASCII art into a list of 16 colour numbers."""
    if len(row) != SPR_W:
        raise ValueError(
            "%s row %d is %d chars, expected %d: %r"
            % (label, y, len(row), SPR_W, row))
    out = []
    for x, ch in enumerate(row):
        if ch in ".  0":
            out.append(0)
        elif ch in "123":
            out.append(int(ch))
        else:
            raise ValueError("%s row %d col %d: bad char %r"
                             % (label, y, x, ch))
    return out


def encode_cell(pixels):
    """Encode 4 pixels into an interleaved MODE 5 (data, mask) byte pair."""
    data = 0
    mask = 0
    for k, c in enumerate(pixels):
        data |= ((c >> 1) & 1) << (7 - k)
        data |= (c & 1) << (3 - k)
        if c == 0:
            mask |= 1 << (7 - k)
            mask |= 1 << (3 - k)
    return data, mask


def encode_sprite(art, label):
    """Encode 16 rows of art into 128 bytes: 16 rows x 4 (data, mask) pairs."""
    if len(art) != SPR_H:
        raise ValueError("%s has %d rows, expected %d" % (label, len(art), SPR_H))
    rows = []
    for y, line in enumerate(art):
        px = parse_row(line, label, y)
        cells = []
        for cx in range(CELLS):
            cells.append(encode_cell(px[cx * 4:cx * 4 + 4]))
        rows.append(cells)
    return rows


def self_test():
    """The sanity values from the format spec."""
    assert encode_cell([1, 1, 1, 1]) == (0x0F, 0x00)
    assert encode_cell([2, 2, 2, 2]) == (0xF0, 0x00)
    assert encode_cell([3, 3, 3, 3]) == (0xFF, 0x00)
    assert encode_cell([0, 0, 0, 0]) == (0x00, 0xFF)
    assert encode_cell([0, 1, 0, 3])[1] == 0xAA


# ---------------------------------------------------------------------------
# Emit
# ---------------------------------------------------------------------------

HEADER = """\\ ============================================================================
\\ DAREDEVIL DEMIS -- sprite data
\\
\\ GENERATED FILE -- DO NOT HAND-EDIT.
\\ Produced by tools/gen_sprites.py, which holds the artwork as ASCII art.
\\ Regenerate with:  python3 tools/gen_sprites.py
\\
\\ Each sprite is 16x16 pixels = 4 CRTC cells by 16 pixel rows, stored as
\\ 16 rows of 4 interleaved (data, mask) byte pairs -- 128 bytes per sprite.
\\ Blit is:  screen = (screen AND mask) OR data
\\ ============================================================================

"""


def emit(sprites):
    lines = [HEADER]
    for idx, (label, name, art) in enumerate(sprites):
        rows = encode_sprite(art, label)
        lines.append("\\ " + "-" * 74 + "\n")
        lines.append("\\ %2d  %s -- %s\n" % (idx, label, name))
        lines.append("\\\n")
        for line in art:
            lines.append("\\     %s\n" % line.replace(" ", "."))
        lines.append("\\ " + "-" * 74 + "\n")
        lines.append(".%s\n" % label)
        for cells in rows:
            body = ",".join("&%02X,&%02X" % (d, m) for d, m in cells)
            lines.append("    EQUB %s\n" % body)
        lines.append("\n")

    labels = [s[0] for s in sprites]
    lines.append("\\ " + "-" * 74 + "\n")
    lines.append("\\ Sprite address lookup, indexed by the SPR_* ids in defs.asm.\n")
    lines.append("\\ " + "-" * 74 + "\n")
    for half in ("LO", "HI"):
        lines.append(".sprite_%s\n" % half.lower())
        for i in range(0, len(labels), 4):
            chunk = labels[i:i + 4]
            lines.append("    EQUB %s\n"
                         % ", ".join("%s(%s)" % (half, l) for l in chunk))
    return "".join(lines)


def main():
    self_test()
    out = sys.argv[1] if len(sys.argv) > 1 else "src/sprites.asm"
    text = emit(SPRITES)
    with open(out, "w") as f:
        f.write(text)
    print("wrote %s: %d sprites, %d bytes of data"
          % (out, len(SPRITES), len(SPRITES) * 128))


if __name__ == "__main__":
    main()
